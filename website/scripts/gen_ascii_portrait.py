"""Regenerate src/data/asciiPortrait.ts from public/profile.jpg.

Each output character is a brightness level ("0"-"9") or a space (background).
AsciiPortrait.tsx maps levels to glyphs and opacity at render time.

Usage: pip install pillow numpy scipy && python3 scripts/gen_ascii_portrait.py
"""
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "public" / "profile.jpg"
OUT = ROOT / "src" / "data" / "asciiPortrait.ts"

COLS = 100
CROP = (300, 220, 1250, 1411)  # left, top, right, bottom in px
CHAR_ASPECT = 0.5  # monospace cells are ~2x taller than wide
TONE_WEIGHT = 0.8  # remainder goes to edge strength

a = np.asarray(Image.open(SRC).convert("L").crop(CROP)).astype(float) / 255

# Keep only the largest bright blob (the subject) so the night sky stays empty.
mask = ndimage.gaussian_filter(a, 8) > 0.05
labels, n = ndimage.label(mask)
sizes = ndimage.sum(mask, labels, range(1, n + 1))
subject = ndimage.binary_fill_holes(labels == (np.argmax(sizes) + 1))
subject = ndimage.binary_dilation(subject, iterations=6)

tone = a**0.45
mu = ndimage.gaussian_filter(tone, 40)
sd = np.sqrt(ndimage.gaussian_filter((tone - mu) ** 2, 40)) + 0.04
local = np.clip(0.5 + (tone - mu) / (3 * sd), 0, 1)
soft = ndimage.gaussian_filter(a**0.5, 2)
edges = np.hypot(ndimage.sobel(soft, 0), ndimage.sobel(soft, 1))
edges = np.clip(edges / np.percentile(edges[subject], 97), 0, 1)

v = TONE_WEIGHT * (0.5 * tone + 0.5 * local) + (1 - TONE_WEIGHT) * edges
v = np.where(subject, v, 0)
v = np.clip(v / np.percentile(v[subject], 99), 0, 1)

h, w = v.shape
rows = int(COLS * (h / w) * CHAR_ASPECT)
grid = np.asarray(Image.fromarray((v * 255).astype("uint8")).resize((COLS, rows), Image.LANCZOS)) / 255

lines = ["".join(" " if x < 0.06 else str(min(9, int(x * 10))) for x in row).rstrip() for row in grid]
while lines and not lines[0]:
    lines.pop(0)

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(
    "// Generated by scripts/gen_ascii_portrait.py from public/profile.jpg. Do not edit by hand.\n"
    "export const portraitRows: string[] = [\n"
    + "".join(f'  "{line}",\n' for line in lines)
    + "];\n"
)
print(f"wrote {OUT} ({COLS}x{len(lines)})")
